import { expect, test, type Page } from '@playwright/test'

async function saved(page: Page) { return page.evaluate(() => JSON.parse(localStorage.getItem('glyph-keepers.save.v1')!)) }
async function finishRun(page: Page) {
  const surface = page.getByRole('textbox', { name: /Typing challenge/ })
  for (let encounter = 0; encounter < 10; encounter++) {
    await expect(surface).toHaveAttribute('aria-readonly', 'false')
    const target = await surface.getAttribute('aria-description')
    await page.keyboard.type(target!, { delay: 10 })
    if (encounter < 9) await expect(page.locator('.progress-track b')).toHaveText(`${encounter + 2} / 10`)
  }
  await expect(page.getByRole('button', { name: 'Hatch your egg' })).toBeVisible()
}

test('typing, error recovery, pause, persisted egg, hatch and companion loop', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByRole('button', { name: 'Begin expedition' }).click()
  const surface = page.getByRole('textbox', { name: /Typing challenge/ })
  await expect(surface).toBeFocused()
  await page.keyboard.type('!!')
  await expect(page.locator('.hearts .lost')).toHaveCount(1)
  await page.keyboard.press('Backspace')
  await page.keyboard.press('Backspace')
  await expect(surface).toHaveAttribute('aria-invalid', 'false')
  await surface.dispatchEvent('keydown', { key: '!', repeat: true })
  await surface.dispatchEvent('paste')
  await surface.dispatchEvent('drop')
  await surface.dispatchEvent('compositionstart')
  await page.keyboard.type('a')
  await surface.dispatchEvent('compositionend')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toBeVisible()
  expect((await saved(page)).totals.attempts).toBe(2)
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: 'Continue adventure' })).toBeFocused()
  await page.getByRole('button', { name: 'Continue adventure' }).click()
  await finishRun(page)
  const before = await saved(page)
  expect(before.totals.wins).toBe(1)
  expect(before.pending.creatureId).toBeTruthy()
  expect(Object.keys(before.collection)).toHaveLength(1)
  expect(before.totals.attempts).toBe(12)
  expect(before.totals.correct).toBe(10)
  await page.reload()
  await expect(page.getByRole('button', { name: 'Hatch your egg' })).toBeVisible()
  expect((await saved(page)).collection).toEqual(before.collection)
  await page.getByRole('button', { name: 'Hatch your egg' }).click()
  await expect(page.getByRole('heading', { name: 'A friendship has hatched.' })).toBeVisible()
  await expect(page.locator('.results-view .pixel-creature')).toHaveCount(1)
  await expect(page.locator('.retreat-art')).toHaveCount(0)
  await page.getByRole('button', { name: 'Meet your collection' }).click()
  await expect(page.locator('.creature-card')).toHaveCount(35)
  await page.getByRole('button', { name: 'Choose companion' }).click()
  expect((await saved(page)).companion).toBe(before.pending.creatureId)
  expect((await saved(page)).pending).toBe(null)
  await page.getByRole('button', { name: 'Parent journal' }).click()
  await expect(page.locator('tbody tr')).toHaveCount(1)
  await page.getByLabel('Reduce motion').check()
  await expect(page.locator('.app-shell')).toHaveClass(/reduce-motion/)
  await page.getByLabel('Keeper name').fill('Rune')
  await page.getByLabel('Keeper name').press('Tab')
  expect((await saved(page)).name).toBe('Rune')
  expect(errors).toEqual([])
})

test('retreat keeps mistakes, gives no egg, and retries with five hearts', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: /Tiny Woods/ }).click()
  await page.getByRole('button', { name: 'Begin expedition' }).click()
  for (let mistake = 0; mistake < 4; mistake++) { await page.keyboard.type('!!'); await page.keyboard.press('Backspace'); await page.keyboard.press('Backspace') }
  await page.keyboard.type('!')
  await expect(page.getByRole('heading', { name: 'Rest, regroup, return.' })).toBeVisible()
  await expect(page.locator('.retreat-art .pixel-creature')).toHaveCount(1)
  const save = await saved(page)
  expect(save.totals.attempts).toBe(9)
  expect(save.totals.wins).toBe(0)
  expect(save.pending).toBe(null)
  expect(save.collection).toEqual({})
  await page.getByRole('button', { name: 'Try a fresh expedition' }).click()
  await expect(page.locator('.hearts .lost')).toHaveCount(0)
  await expect(page.getByRole('textbox', { name: /Typing challenge/ })).toBeFocused()
})

test('malformed saves recover and layouts fit narrow screens with reduced motion', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('glyph-keepers.save.v1', '{broken'))
  await page.setViewportSize({ width: 390, height: 844 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await expect(page.getByRole('alert')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.getByRole('button', { name: 'Collection', exact: false }).click()
  await expect(page.locator('.creature-card')).toHaveCount(35)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.getByRole('button', { name: 'Parent journal' }).click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})

test('hiding the browser pauses combat until the player explicitly resumes', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Begin expedition' }).click()
  await page.evaluate(() => { Object.defineProperty(document, 'hidden', { configurable: true, value: true }); document.dispatchEvent(new Event('visibilitychange')) })
  await expect(page.getByRole('dialog')).toBeVisible()
  const before = await saved(page)
  await page.waitForTimeout(300)
  await page.keyboard.type('!')
  expect((await saved(page)).totals).toEqual(before.totals)
  await page.evaluate(() => { delete (document as unknown as { hidden?: boolean }).hidden; document.dispatchEvent(new Event('visibilitychange')) })
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('button', { name: 'Continue adventure' }).click()
  await expect(page.getByRole('textbox', { name: /Typing challenge/ })).toBeFocused()
})
